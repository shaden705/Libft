#include "libft.h"

int	ft_isalnum(int f)
{
	if ((f >= 'a' && f <= 'z') || (f >= 'A' && f <= 'Z'))
		return (1);
	else if (f >= '0' && f <= '9')
		return (1);
	else
		return (0);
}
